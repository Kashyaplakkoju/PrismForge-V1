// Reproduce additional actual preset BufferGeometry from the user's local project.
// No packages are installed; the original checkout is read-only.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const reference = path.resolve(process.argv[2] ?? 'D:/glasses-tryon-v2');
const outputRoot = path.resolve(process.argv[3] ?? repo);
const meshRelative = 'windows/src/effects/overlays/reference_glasses_collection_mesh.inc';
const manifestRelative = 'tools/accessories/reference_glasses_collection_provenance.json';
const digest = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const THREE = await import(pathToFileURL(path.join(reference, 'node_modules/three/build/three.module.js')).href);
const { GlassesModel } = await import(pathToFileURL(path.join(reference, 'src/glasses/glasses-model.js')).href);
// storage.js catches the unavailable browser thumbnail canvas in this Node process.
// Its actual catalogue exports are used, rather than duplicating the preset options.
const { DEFAULT_PRESETS } = await import(pathToFileURL(path.join(reference, 'src/processing/storage.js')).href);
const selected = [{id:'aviator', nativeStyle:1, symbol:'Aviator'}, {id:'round_tortoise', nativeStyle:2, symbol:'RoundTortoise'}, {id:'cateye', nativeStyle:3, symbol:'CatEye'}];
const finite = value => {
  if (!Number.isFinite(value)) throw new Error('Non-finite reference mesh value');
  return Math.fround(value);
};
const floatLiteral = v => {
  const value = Object.is(v, -0) ? 0 : v;
  const s = value.toPrecision(9).replace(/(\.\d*?)0+(?=e|$)/, '$1').replace(/\.(?=e|$)/, '.0');
  return `${s}f`;
};
const content = [
  '// Generated by tools/accessories/export_reference_glasses_collection.mjs.',
  '// Exact additional preset geometry from the user-provided glasses-tryon-v2.',
  '// Full mesh transforms/topology preserved; only coincident zero normals repaired.',
  '// See tools/accessories/reference_glasses_collection_provenance.json. Do not edit.',
];
const presets = [];
for (const entry of selected) {
  const preset = DEFAULT_PRESETS.find(p => p.id === entry.id);
  if (!preset || preset.type !== 'preset') throw new Error('Required original preset missing: ' + entry.id);
  const options = { id:preset.id, styleId:preset.id, material:preset.material, frameColor:preset.frameColor, templeColor:preset.templeColor, lensTint:preset.lensTint, lensOpacity:preset.lensOpacity };
  const model = new GlassesModel(options);
  model.group.updateMatrixWorld(true);
  const vertices = [], triangles = [], components = [], normalRepairs = [];
  const envelope = { min:[Infinity,Infinity,Infinity], max:[-Infinity,-Infinity,-Infinity] };
  model.group.traverse(child => {
    if (!child.isMesh) return;
    const geometry = child.geometry, position = geometry.getAttribute('position'), normal = geometry.getAttribute('normal'), uv = geometry.getAttribute('uv');
    if (!position || !normal || position.count !== normal.count) throw new Error('Missing or inconsistent reference geometry');
    const base = vertices.length, firstTriangle = triangles.length;
    const material = child.name === 'Lens' ? 'Lens' : child.name === 'NosePad' ? 'NosePad' : 'Frame';
    const normalMatrix = new THREE.Matrix3().getNormalMatrix(child.matrixWorld);
    for (let i=0; i<position.count; ++i) {
      const p = new THREE.Vector3().fromBufferAttribute(position,i).applyMatrix4(child.matrixWorld);
      const n = new THREE.Vector3().fromBufferAttribute(normal,i).applyMatrix3(normalMatrix).normalize();
      if (n.lengthSq()<1e-12) {
        let coincident=-1;
        for(let j=0;j<position.count;++j) {
          if(position.getX(j)!==position.getX(i)||position.getY(j)!==position.getY(i)||position.getZ(j)!==position.getZ(i)) continue;
          const candidate=new THREE.Vector3().fromBufferAttribute(normal,j).applyMatrix3(normalMatrix).normalize();
          if(candidate.lengthSq()>.99){n.copy(candidate);coincident=j;break;}
        }
        if(coincident<0) throw new Error('Reference zero normal has no coincident valid surface normal');
        normalRepairs.push({component:child.name,componentOrdinal:components.length,vertex:i,copiedNormalFromCoincidentVertex:coincident});
      }
      const values=[p.x,p.y,p.z,n.x,n.y,n.z,uv?uv.getX(i):0,uv?uv.getY(i):0].map(finite);
      if(values.slice(0,3).some(v=>Math.abs(v)>4)) throw new Error('Reference position exceeds bounded native coordinate contract');
      for(let j=0;j<3;++j){envelope.min[j]=Math.min(envelope.min[j],values[j]);envelope.max[j]=Math.max(envelope.max[j],values[j]);}
      vertices.push(values);
    }
    const index=geometry.getIndex(), count=index?index.count:position.count;
    if(count%3!==0) throw new Error('Non-triangular reference geometry');
    for(let i=0;i<count;i+=3){const indices=[0,1,2].map(j=>index?index.getX(i+j):i+j);if(!indices.every(v=>Number.isInteger(v)&&v>=0&&v<position.count))throw new Error('Invalid reference mesh index');triangles.push([...indices.map(v=>base+v),material]);}
    components.push({name:child.name,material,firstVertex:base,vertexCount:position.count,firstTriangle,triangleCount:triangles.length-firstTriangle,materialProperties:{color:`#${child.material.color.getHexString()}`,opacity:child.material.opacity,roughness:child.material.roughness,metalness:child.material.metalness,clearcoat:child.material.clearcoat,transparent:child.material.transparent,depthWrite:child.material.depthWrite}});
  });
  model.dispose();
  if(vertices.length>20000||triangles.length>60000||!vertices.length||!triangles.length)throw new Error('Reference mesh exceeds native bounded contract');
  const materials={};
  for(const component of components){if(!materials[component.material])materials[component.material]=component.materialProperties;else if(JSON.stringify(materials[component.material])!==JSON.stringify(component.materialProperties))throw new Error('Unrepresented component material variation');}
  content.push(`static constexpr MeshVertex kReference${entry.symbol}Vertices[] = {`,...vertices.map(v=>` {${v.map(floatLiteral).join(',')}},`),'};',`static constexpr MeshTriangle kReference${entry.symbol}Triangles[] = {`,...triangles.map(t=>` {${t[0]}u,${t[1]}u,${t[2]}u,Material::${t[3]}},`),'};');
  const rgba=key=>{const props=materials[key];const hex=props.color.slice(1);return [0,2,4].map(i=>parseInt(hex.slice(i,i+2),16)/255).concat(props.opacity);};
  content.push(`static constexpr GlassesMaterialSet kReference${entry.symbol}Materials{`, ` {${rgba('Frame').map(floatLiteral).join(',')}},`, ` {${rgba('Lens').map(floatLiteral).join(',')}},`, ` {${rgba('NosePad').map(floatLiteral).join(',')}},`, ` ${floatLiteral(materials.Frame.roughness)},${floatLiteral(materials.Frame.metalness)},${floatLiteral(materials.Lens.roughness)},${floatLiteral(preset.scaleMultiplier ?? 1)}`, '};');
  presets.push({nativeStyle:entry.nativeStyle,id:entry.id,name:preset.name,options,frameScaleCentimeters:14,scaleMultiplier:preset.scaleMultiplier??1,vertices:vertices.length,triangles:triangles.length,envelope,components,normalRepairs,materials});
}
content.push('');
const output=path.join(outputRoot,meshRelative),manifestPath=path.join(outputRoot,manifestRelative);
fs.mkdirSync(path.dirname(output),{recursive:true});fs.mkdirSync(path.dirname(manifestPath),{recursive:true});
fs.writeFileSync(output,content.join('\n'),'utf8');
const sources=['src/glasses/glasses-model.js','src/glasses/pose-estimator.js','src/processing/storage.js','src/glasses/texture-factory.js','src/rendering/scene-manager.js','src/app.js','package.json','package-lock.json','node_modules/three/package.json','node_modules/three/build/three.module.js','node_modules/three/build/three.core.js'].map(file=>({path:file,sha256:digest(path.join(reference,file))}));
const manifest={schemaVersion:1,referenceRoot:reference.replaceAll('\\','/'),source:'User-provided glasses-tryon-v2; actual additional wired preset GlassesModel meshes',exportScript:{path:'tools/accessories/export_reference_glasses_collection.mjs',sha256:digest(fileURLToPath(import.meta.url))},presets,sources,output:{path:meshRelative,sha256:digest(output)},scope:'Exact source geometry/topology and actual wired solid material colours/opacity. Catalogue SVG/canvas previews are not runtime mesh textures; native lighting approximates the Three.js renderer. Original Classic Wayfarer export is untouched.'};
fs.writeFileSync(manifestPath,JSON.stringify(manifest,null,2)+'\n','utf8');
console.log(JSON.stringify({output:manifest.output,presets:presets.map(p=>({nativeStyle:p.nativeStyle,name:p.name,vertices:p.vertices,triangles:p.triangles,components:p.components.length,normalRepairs:p.normalRepairs.length}))},null,2));
